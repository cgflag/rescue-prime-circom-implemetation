function mod(value) {
  const reduced = value % FIELD_PRIME;
  return reduced >= 0n ? reduced : reduced + FIELD_PRIME;
}

function powMod(base, exp) {
  let result = 1n;
  let cur = mod(base);
  let e = exp;

  while (e > 0n) {
    if (e & 1n) result = mod(result * cur);
    cur = mod(cur * cur);
    e >>= 1n;
  }

  return result;
}

function mix(state) {
  return MDS.map((row) => mod(row.reduce((sum, value, idx) => sum + value * state[idx], 0n)));
}

function permutation(inputState) {
  let state = inputState.map(mod);

  for (let round = 0; round < ROUNDS; round += 1) {
    state = state.map((value) => powMod(value, ALPHA));
    state = mix(state);
    state = state.map((value, idx) => mod(value + ROUND_CONSTANTS[round * 2 * STATE_WIDTH + idx]));
    state = state.map((value) => powMod(value, ALPHA_INV));
    state = mix(state);
    state = state.map((value, idx) => mod(value + ROUND_CONSTANTS[round * 2 * STATE_WIDTH + STATE_WIDTH + idx]));
  }

  return state;
}

function hash(inputs) {
  let state = [0n, 0n];
  const padded = inputs.map(BigInt).concat(1n);

  for (const block of padded) {
    state[0] = mod(state[0] + block);
    state = permutation(state);
  }

  return state[0];
}

